document.addEventListener("DOMContentLoaded", () => {


    /* =========================================
       ELEMENTS
    ========================================== */

    const productsGrid =
        document.getElementById("productsGrid");

    const emptyProducts =
        document.getElementById("emptyProducts");

    const productSearch =
        document.getElementById("productSearch");

    const toast =
        document.getElementById("toast");


    /* =========================================
       FACTORY SECTION
    ========================================== */

    const selectedSection =
        "منتجات المصنع";


    /* =========================================
       CHECK
    ========================================== */

    if (!productsGrid) {

        console.error(
            "VOLTA: productsGrid not found."
        );

        return;
    }


    /* =========================================
       TOAST
    ========================================== */

    function showToast(message) {

        if (!toast) return;


        toast.textContent =
            message;


        toast.classList.add("show");


        clearTimeout(
            window.factoryToastTimer
        );


        window.factoryToastTimer =
            setTimeout(() => {

                toast.classList.remove("show");

            }, 2200);

    }


    /* =========================================
       RENDER PRODUCTS
    ========================================== */

    function renderProducts(products) {

        productsGrid.innerHTML = "";


        /* No Products */

        if (!products || products.length === 0) {

            if (emptyProducts) {

                emptyProducts.hidden =
                    false;

            }

            return;
        }


        /* Hide Empty */

        if (emptyProducts) {

            emptyProducts.hidden =
                true;

        }


        /* Create Cards */

        products.forEach(product => {


            const card =
                document.createElement("article");


            card.className =
                "product-card";


            card.innerHTML = `

                <!-- =====================
                     IMAGE
                ====================== -->

                <div class="product-image-wrapper">

                    <span class="product-number">
                        #${String(product.id).padStart(2, "0")}
                    </span>


                    <img
                        class="product-image"
                        src="${product.image}"
                        alt="${product.name}"
                        loading="lazy"
                        onerror="
                            this.onerror=null;
                            this.src='assets/products/placeholder.webp';
                        "
                    >

                </div>


                <!-- =====================
                     INFO
                ====================== -->

                <div class="product-info">

                    <h3>
                        ${product.name}
                    </h3>


                    <span class="product-unit">
                        ${product.unit}
                    </span>

                </div>


                <!-- =====================
                     ACTIONS
                ====================== -->

                <div class="product-actions">


                    <div class="quantity-row">


                        <div class="quantity-box">


                            <!-- MINUS -->

                            <button
                                type="button"
                                class="quantity-btn quantity-minus"
                                aria-label="تقليل الكمية"
                            >
                                −
                            </button>


                            <!-- INPUT -->

                            <input
                                type="number"
                                class="product-quantity"
                                value="0"
                                min="0"
                                step="1"
                                inputmode="numeric"
                                aria-label="الكمية"
                            >


                            <!-- PLUS -->

                            <button
                                type="button"
                                class="quantity-btn quantity-plus"
                                aria-label="زيادة الكمية"
                            >
                                +
                            </button>


                        </div>


                        <span class="quantity-unit">
                            ${product.unit}
                        </span>


                    </div>


                    <!-- ADD TO CART -->

                    <button
                        type="button"
                        class="add-to-cart"
                        data-product-id="${product.id}"
                    >

                        <span>
                            🛒
                        </span>


                        <span>
                            إضافة للسلة
                        </span>

                    </button>


                </div>

            `;


            productsGrid.appendChild(card);

        });

    }


    /* =========================================
       INITIAL RENDER
    ========================================== */

    renderProducts(
        factoryProducts
    );


    /* =========================================
       SEARCH
    ========================================== */

    if (productSearch) {


        productSearch.addEventListener(
            "input",
            () => {


                const searchValue =
                    productSearch.value
                    .trim()
                    .toLowerCase();


                const filteredProducts =
                    factoryProducts.filter(
                        product => {

                            return product.name
                                .toLowerCase()
                                .includes(
                                    searchValue
                                );

                        }
                    );


                renderProducts(
                    filteredProducts
                );

            }
        );

    }


    /* =========================================
       PRODUCT BUTTONS
    ========================================== */

    productsGrid.addEventListener(
        "click",
        event => {


            /* =================================
               PLUS / MINUS
            ================================= */

            const quantityButton =
                event.target.closest(
                    ".quantity-btn"
                );


            if (quantityButton) {


                const quantityBox =
                    quantityButton.closest(
                        ".quantity-box"
                    );


                if (!quantityBox) return;


                const input =
                    quantityBox.querySelector(
                        ".product-quantity"
                    );


                if (!input) return;


                let quantity =
                    parseInt(
                        input.value,
                        10
                    );


                if (isNaN(quantity)) {

                    quantity = 0;

                }


                /* PLUS */

                if (
                    quantityButton.classList.contains(
                        "quantity-plus"
                    )
                ) {

                    quantity++;

                }


                /* MINUS */

                if (
                    quantityButton.classList.contains(
                        "quantity-minus"
                    )
                ) {

                    quantity--;

                }


                /* Never below zero */

                quantity =
                    Math.max(
                        0,
                        quantity
                    );


                input.value =
                    quantity;


                return;

            }


            /* =================================
               ADD TO CART
            ================================= */

            const addButton =
                event.target.closest(
                    ".add-to-cart"
                );


            if (!addButton) return;


            const productId =
                Number(
                    addButton.dataset.productId
                );


            const product =
                factoryProducts.find(
                    item =>
                    item.id === productId
                );


            if (!product) {

                console.error(
                    "VOLTA: Product not found:",
                    productId
                );

                return;

            }


            const card =
                addButton.closest(
                    ".product-card"
                );


            if (!card) return;


            const quantityInput =
                card.querySelector(
                    ".product-quantity"
                );


            if (!quantityInput) return;


            let quantity =
                parseInt(
                    quantityInput.value,
                    10
                );


            if (isNaN(quantity)) {

                quantity = 0;

            }


            /* Quantity Required */

            if (quantity <= 0) {

                showToast(
                    "حدد الكمية أولاً"
                );


                quantityInput.focus();


                return;

            }


            /* Check Cart */

            if (
                typeof addToCart !==
                "function"
            ) {

                console.error(
                    "VOLTA: addToCart function not found."
                );


                showToast(
                    "حدث خطأ في السلة"
                );


                return;

            }


            /* Add */

            addToCart({

                id: product.id,

                name: product.name,

                image: product.image,

                unit: product.unit,

                quantity: quantity,

                section: selectedSection

            });


            /* Success */

            showToast(
                `تم إضافة ${product.name} × ${quantity} للسلة`
            );


            /* Reset */

            quantityInput.value =
                0;

        }

    );


    /* =========================================
       MANUAL QUANTITY INPUT
    ========================================== */

    productsGrid.addEventListener(
        "input",
        event => {


            if (!event.target.classList.contains(
                    "product-quantity"
                )) {

                return;

            }


            let value =
                event.target.value;


            value =
                value.replace(
                    /[^0-9]/g,
                    ""
                );


            let quantity =
                parseInt(
                    value,
                    10
                );


            if (isNaN(quantity)) {

                quantity = 0;

            }


            if (quantity < 0) {

                quantity = 0;

            }


            event.target.value =
                quantity;

        }
    );


    /* =========================================
       ESC SEARCH
    ========================================== */

    if (productSearch) {


        productSearch.addEventListener(
            "keydown",
            event => {


                if (
                    event.key === "Escape"
                ) {


                    productSearch.value =
                        "";


                    renderProducts(
                        factoryProducts
                    );

                }

            }
        );

    }


    /* =========================================
       GLOBAL
    ========================================== */

    window.getSelectedFactorySection =
        function() {

            return selectedSection;

        };


    window.selectedFactorySection =
        selectedSection;


    /* =========================================
       DONE
    ========================================== */

    console.log(
        `VOLTA Factory: ${factoryProducts.length} products loaded successfully.`
    );

});